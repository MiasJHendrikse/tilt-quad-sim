% =====================================================================
function setMatlabFcnCode(blkPath, code)
% Inject MATLAB code into a MATLAB Function (Stateflow EMChart) block.
    rt    = sfroot;
    chart = rt.find('-isa', 'Stateflow.EMChart', '-and', 'Path', blkPath);
    if isempty(chart)
        open_system(blkPath);
        chart = rt.find('-isa', 'Stateflow.EMChart', '-and', 'Path', blkPath);
    end
    chart.Script = code;
end

function add_logging_block(mdl, srcPort, blkName, varName)
% Add a To Workspace block and connect it to a signal already on the diagram.
    blkPath = [mdl '/' blkName];
    add_block('simulink/Sinks/To Workspace', blkPath);
    set_param(blkPath, 'VariableName', varName, 'SaveFormat', 'Timeseries');
    tokens  = regexp(srcPort, '^([^/]+)/(\d+)$', 'tokens', 'once');
    portIdx = str2double(tokens{2});
    add_line(mdl, [tokens{1} '/' num2str(portIdx)], [blkName '/1'], 'autorouting', 'on');
end
